function applyLanguage(lang) {
  const dict = translations[lang];
  if (!dict) return;

  document.documentElement.lang = lang;

  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key || !(key in dict)) return;

    const value = dict[key];
    if (typeof value === "string" && value.includes("\n")) {
      el.innerHTML = "";
      value.split("\n\n").forEach((block, index) => {
        const p = document.createElement("p");
        p.textContent = block;
        if (index === 0) {
          el.appendChild(p);
        } else {
          el.appendChild(p);
        }
      });
    } else {
      el.textContent = value;
    }
  });

  document
    .querySelectorAll(".lang-btn")
    .forEach((btn) => btn.classList.toggle("is-active", btn.dataset.lang === lang));
}

document.addEventListener("DOMContentLoaded", () => {
  // Initial language: Russian for ru-locale users, otherwise English
  const browserLang = (
    navigator.language ||
    navigator.userLanguage ||
    ""
  ).toLowerCase();
  const initialLang = browserLang.startsWith("ru") ? "ru" : "en";
  applyLanguage(initialLang);

  // Switcher
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.dataset.lang;
      applyLanguage(lang);
    });
  });

  const revealItems = document.querySelectorAll("[data-reveal]");
  const prefersReducedMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)"
  ).matches;

  if (!prefersReducedMotion && "IntersectionObserver" in window) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            observer.unobserve(entry.target);
          }
        });
      },
      {
        threshold: 0.2,
      }
    );

    revealItems.forEach((el, index) => {
      el.style.transitionDelay = `${index * 0.06}s`;
      observer.observe(el);
    });
  } else {
    revealItems.forEach((el) => {
      el.classList.add("is-visible");
    });
  }
});

